# Python data types

# Text
name = "Rakshit"

# Numbers
age = 25                 # int
height = 5.9             # float
complex_number = 2 + 3j  # complex

# Boolean values
is_learning = True

# Collections
skills = ["Python", "AI", "ML"]       # list: ordered and changeable
coordinates = (28.6, 77.2)              # tuple: ordered and unchangeable
unique_numbers = {1, 2, 2, 3}           # set: unique values
student = {"name": name, "age": age}   # dict: key-value pairs

# A variable can also contain no value.
optional_value = None

print("Python data types demo")
print("String:", name)
print("Integer:", age)
print("Float:", height)
print("Complex:", complex_number)
print("Boolean:", is_learning)
print("List:", skills)
print("Tuple:", coordinates)
print("Set:", unique_numbers)
print("Dictionary:", student)
print("None:", optional_value)